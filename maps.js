  const icon = L.divIcon({
    className: "geo-pin-wrap",
    html: '<span class="geo-pin" aria-hidden="true"></span>',
    iconSize: [20,20],
    iconAnchor: [10,19],
    popupAnchor: [0,-18]
  });

