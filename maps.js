    const data = maps[figure.dataset.map];
    const canvas = figure.querySelector(".map-canvas");
    if (!data || !canvas) return;

    figure.querySelector(".map-title").textContent = data.title;
    figure.querySelector(".map-caption").textContent = data.caption + " 地图数据与栅格瓦片：OpenStreetMap贡献者。";

